// ZEO 1.25.0 – env.js for the mobile app (runs after `ng build`, before `npx cap sync`).
// The app keeps the server chosen on its first screen in localStorage (zeo_server); the browser build is not changed.
//   ZEO_CLOUD_URL  – address of ZEO Cloud offered on the first screen (default https://app.zeocloud.ae)
//   push notifications are switched on when android/app/google-services.json exists (Firebase project of Adept)
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const web = 'dist/hrms-project/browser';
const cloud = (process.env.ZEO_CLOUD_URL || 'https://app.zeocloud.ae').replace(/\/+$/, '');
const push = existsSync(join('android', 'app', 'google-services.json'));
const js = `// ZEO mobile app (generated by scripts/mobile-env.mjs – do not edit in the app)
window.ZEO_API_URL = (window.Capacitor && localStorage.getItem('zeo_server')) || '';
window.ZEO_CLOUD_URL = ${JSON.stringify(cloud)};
window.ZEO_PUSH = ${push};
`;
if (!existsSync(web)) { console.error(`Build the app first: ${web} is missing (npm run mobile:build).`); process.exit(1); }
writeFileSync(join(web, 'assets', 'env.js'), js);
console.log(`env.js written – cloud ${cloud}, push ${push ? 'on (google-services.json found)' : 'off (no android/app/google-services.json)'}`);
